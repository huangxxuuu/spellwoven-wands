"""Build DST's legacy FMOD events from the supplied, unmodified per-note WAVs."""
import argparse
import hashlib
import json
import shutil
import subprocess
import tempfile
import uuid
import wave
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets_src/audio/instruments'
NAME = 'nw_instruments'
DEFAULT_DESIGNER = Path("E:/SteamLibrary/steamapps/common/Don't Starve Mod Tools/mod_tools/FMOD_Designer/fmod_designercl.exe")


def node(parent, tag, value=None):
    result = ET.SubElement(parent, tag)
    if value is not None:
        result.text = str(value)
    return result


def props(parent, **values):
    for key, value in values.items():
        node(parent, key, value)


def guid(parent, name):
    node(parent, 'guid', '{' + str(uuid.uuid5(uuid.NAMESPACE_URL, NAME + '/' + name)) + '}')


def import_zip(path):
    with zipfile.ZipFile(path) as archive:
        for entry in archive.namelist():
            if entry.endswith('/'):
                continue
            relative = Path(entry).relative_to('DST_Instrument_WAVs')
            # Import only reusable samples, manifests and provenance, not preview/SF2 files.
            if '..' in relative.parts or relative.is_absolute():
                raise ValueError(entry)
            if not (relative.suffix == '.json' and len(relative.parts) == 1
                    or relative.parts[0] in ('ocarina', 'lyre', 'licenses')
                    or relative.parts[0] == 'sources' and relative.suffix in ('.txt', '.json')):
                continue
            target = SOURCE / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(archive.read(entry))
    (SOURCE / 'import.json').write_text(json.dumps({
        'archive': path.name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        'samples_modified': False,
    }, indent=2) + '\n', encoding='utf8')


def build(designer):
    mapping = json.loads((SOURCE / 'note_map.json').read_text(encoding='utf8'))
    project = ET.Element('project')
    props(project, name=NAME, version=4, eventgroup_nextid=2, soundbank_nextid=1,
          sounddef_nextid=76, build_project=1, build_continue_on_error=0,
          currentbank=NAME, currentlanguage='default', primarylanguage='default', language='default')
    guid(project, 'project')
    folder = node(project, 'sounddeffolder')
    props(folder, name='master')
    guid(folder, 'master')
    bank = node(project, 'soundbank')
    props(bank, name=NAME, _PC_banktype='DecompressedSample', _PC_format='PCM',
          _PC_forcesoftware=1, _PC_quality=100, _PC_build=1)
    guid(bank, 'bank')
    output = {'project': NAME, 'instruments': {}}
    lua = ['-- Generated by tools/build_instrument_audio.py; pitch is measured from C3 (MIDI 48).', 'return {']
    for instrument in mapping['instruments']:
        source_name = instrument['instrument']
        runtime_name = 'kantele' if source_name == 'lyre' else source_name
        manifest = json.loads((SOURCE / (source_name + '_manifest.json')).read_text(encoding='utf8'))
        expected = {n['midi']: n for n in manifest['notes']}
        assert [n['midi'] for n in instrument['notes']] == list(range(instrument['midi_min'], instrument['midi_max'] + 1))
        group = node(project, 'eventgroup')
        props(group, name=runtime_name, event_nextid=instrument['note_count'], eventgroup_nextid=0)
        guid(group, runtime_name)
        lua.append('    %s={min=%d,max=%d,range="%s–%s",samples={' % (
            runtime_name, instrument['midi_min'] - 48, instrument['midi_max'] - 48,
            instrument['note_min'], instrument['note_max']))
        entries = []
        for note in instrument['notes']:
            midi = note['midi']
            filename = note['relative_path']
            sample = SOURCE / filename
            digest = hashlib.sha256(sample.read_bytes()).hexdigest()
            assert digest == expected[midi]['sha256'], sample
            with wave.open(str(sample)) as wav:
                assert (wav.getnchannels(), wav.getsampwidth(), wav.getframerate()) == (1, 2, 44100)
                duration = wav.getnframes() / wav.getframerate()
            event_name = 'm%03d' % midi
            event_path = '/'.join((NAME, runtime_name, event_name))
            sound_name = runtime_name + '_' + event_name
            sounddef = node(folder, 'sounddef')
            props(sounddef, name=sound_name, type='randomnorepeat', mode=0, pitch=0,
                  pitch_randomization=0, volume_db=0, volume_randomization=0, spawncount=0)
            guid(sounddef, sound_name)
            waveform = node(sounddef, 'waveform')
            props(waveform, filename=filename, soundbankname=NAME, weight=100)
            bank_wave = node(bank, 'waveform')
            props(bank_wave, filename=filename, _PC_resamplemode=0)
            simple = node(group, 'simpleevent')
            event = node(simple, 'event')
            props(event, name=event_name, parameter_nextid=0, layer_nextid=1)
            guid(event, event_path)
            layer = node(event, 'layer')
            props(layer, name='layer00', height=100, mute=0, solo=0, _PC_enable=1)
            sound = node(layer, 'sound')
            # A single playback needs an explicit zero repeat count. Event.oneshot
            # alone does not prevent the underlying sample from looping forever.
            props(sound, name=sound_name, x=0, width=1, startmode=1, loopmode=0,
                  loopcount2=0, autopitchenabled=0, finetune=0, volume=1)
            props(event, volume_db=0, pitch=0, pitch_randomization=0, volume_randomization=0,
                  priority=128, maxplaybacks=32, maxplaybacks_behavior='Steal_oldest',
                  mode='x_3d', rolloff='Linear', mindistance=2, maxdistance=30,
                  headrelative='World_relative', oneshot='Yes', category='master',
                  doppler_scale=0, reverbdrylevel_db=0, reverblevel_db=-60, _PC_enabled=1)
            props(simple, playcount=1, loopcount=0, queuedsounds=1, polyphony=1,
                  totalgrains=0, bankname=NAME, _PC_resamplemode='Off')
            lua.append('        [%d]={event="%s",duration=%.6f},' % (midi - 48, event_path, duration))
            entries.append(dict(midi=midi, note=note['note'], event=event_path,
                                file=filename, duration=duration, sha256=digest))
        lua.append('    }},')
        output['instruments'][runtime_name] = entries
    lua.append('}')
    ET.indent(project)
    fdp = SOURCE / (NAME + '.fdp')
    ET.ElementTree(project).write(fdp, encoding='utf-8', xml_declaration=True)
    destination = ROOT / 'mod/sound'
    destination.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='nw_audio_') as temporary:
        result = subprocess.run([str(designer), '-pc', '-k', '-K', '-b', temporary,
                                 '-a', str(SOURCE), str(fdp)], capture_output=True, text=True, errors='replace')
        log = result.stdout + result.stderr
        (ROOT / 'test_reports').mkdir(exist_ok=True)
        (ROOT / 'test_reports/instrument_audio_build.log').write_text(log, encoding='utf8')
        if result.returncode or not all((Path(temporary) / (NAME + ext)).is_file() for ext in ('.fev', '.fsb')):
            raise RuntimeError(log)
        for ext in ('.fev', '.fsb'):
            shutil.copyfile(Path(temporary) / (NAME + ext), destination / (NAME + ext))
    for license_file in (SOURCE / 'licenses').iterdir():
        target = destination / 'licenses' / license_file.name
        target.parent.mkdir(exist_ok=True)
        shutil.copyfile(license_file, target)
    (ROOT / 'mod/scripts/nw/instrument_samples.lua').write_text('\n'.join(lua) + '\n', encoding='utf8')
    (SOURCE / 'events.json').write_text(json.dumps(output, indent=2) + '\n', encoding='utf8')
    print('Built 76 PCM events; original WAV hashes and format verified.')
    for ext in ('.fev', '.fsb'):
        print(destination / (NAME + ext), (destination / (NAME + ext)).stat().st_size)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--import-zip', type=Path)
    parser.add_argument('--designer', type=Path, default=DEFAULT_DESIGNER)
    args = parser.parse_args()
    if args.import_zip:
        import_zip(args.import_zip)
    build(args.designer)
