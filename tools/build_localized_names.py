"""Generate cross-language names for networked and legacy saved default names."""
import json
from pathlib import Path
from lupa.lua51 import LuaRuntime

ROOT = Path(__file__).resolve().parents[1]

def names(language):
    lua = LuaRuntime(unpack_returned_tuples=True)
    lua.globals().package.path = (ROOT / 'mod/scripts/?.lua').as_posix() + ';' + lua.globals().package.path
    lua.eval('require("nw/locale").configure')(language, 'en')
    result = dict(lua.eval('require("nw/cards").names').items())
    factory = lua.eval('require("nw/wand_factory")')
    result['wand_starter'] = factory.name(lua.table_from({'starter': True}))
    for tier in range(1, 5):
        for kind in lua.eval('require("nw/definitions").archetypes').values():
            result[f'wand_{tier}_{kind}'] = factory.name(lua.table_from({'tier': tier, 'archetype': kind}))
    return result

if __name__ == '__main__':
    zh, en = names('zh'), names('en')
    assert zh.keys() == en.keys()
    target = ROOT / 'mod/scripts/nw/locales/names.lua'
    rows = dict((value, en[key]) for key, value in zh.items())
    target.write_text('-- Generated by tools/build_localized_names.py; do not edit.\nreturn {\n' + ''.join(
        '    [' + json.dumps(k, ensure_ascii=False) + ']=' + json.dumps(v, ensure_ascii=False) + ',\n'
        for k, v in sorted(rows.items())) + '}\n', encoding='utf8')
    print(f'Generated {len(rows)} bilingual default names')
